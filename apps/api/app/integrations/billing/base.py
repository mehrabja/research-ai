"""Provider-neutral billing adapter contract."""
from __future__ import annotations
import uuid
from typing import Any, Protocol

class BillingProviderError(Exception): ...
class BillingAuthenticationError(BillingProviderError): ...
class BillingRateLimitError(BillingProviderError): ...
class BillingUnavailableError(BillingProviderError): ...
class BillingInvalidRequestError(BillingProviderError): ...

class BillingProvider(Protocol):
    provider_name: str
    def create_customer(self, *, workspace_id: uuid.UUID, owner_user_id: uuid.UUID, email: str, idempotency_key: str | None = None) -> str: ...
    def create_checkout_session(self, *, customer_id: str | None, customer_email: str, price_id: str, workspace_id: uuid.UUID, success_url: str, cancel_url: str, idempotency_key: str) -> dict[str, Any]: ...
    def get_subscription(self, *, subscription_id: str) -> dict[str, Any] | None: ...
    def cancel_subscription(self, *, subscription_id: str, at_period_end: bool = True, idempotency_key: str | None = None) -> None: ...
    def resume_subscription(self, *, subscription_id: str, idempotency_key: str | None = None) -> None: ...
    def update_subscription_price(self, *, subscription_id: str, price_id: str, idempotency_key: str | None = None) -> dict[str, Any]: ...
    def create_portal_session(self, *, customer_id: str, return_url: str) -> str: ...
    def list_invoices(self, *, customer_id: str, limit: int = 20) -> list[dict[str, Any]]: ...
    def verify_webhook(self, *, payload: bytes, signature: str) -> dict[str, Any]: ...
